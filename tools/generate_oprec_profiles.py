"""Generate profile constants from an unmodified vendor oprec_audrec_params directory."""

import argparse
from pathlib import Path
import re


PROFILE_FILE = re.compile(r"^oprec_record_ID([0-9]+)_(.+)\.(?:bin|txt)$", re.IGNORECASE)


def identifier(value):
    value = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if value[0].isdigit():
        value = "config_" + value
    return value


def read_profiles(directory):
    profiles = {}
    names = {}
    for path in sorted(directory.iterdir()):
        match = PROFILE_FILE.fullmatch(path.name)
        if not match:
            continue
        profile_id = int(match.group(1))
        name = identifier(match.group(2)).upper()
        if profile_id in profiles:
            if profiles[profile_id][0] != name:
                raise ValueError(f"{directory}: profile ID {profile_id} names both "
                                 f"{profiles[profile_id][1]} and {path.name}")
            continue
        if name in names:
            raise ValueError(f"{path}: duplicate constant {name} for profile ID {profile_id}")
        profiles[profile_id] = (name, path.name)
        names[name] = profile_id
    if not profiles:
        raise ValueError(f"{directory}: no profile entries found")
    return [(name, profile_id, filename)
            for profile_id, (name, filename) in sorted(profiles.items())]


def generate(directory):
    lines = [
        "// Generated by generate_oprec_profiles.py; do not edit.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "#pragma once",
        "",
        "namespace oprec::profiles {",
        "",
        "enum Profile : int {",
    ]
    for name, value, filename in read_profiles(directory):
        lines.append(f"    {name} = {value},  // {filename}")
    lines.extend(["};", "", "}  // namespace oprec::profiles"])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path, help="vendor oprec_audrec_params directory")
    parser.add_argument("output", type=Path, help="generated header in the device tree")
    args = parser.parse_args()
    try:
        header = generate(args.directory)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    args.output.write_text(header)


if __name__ == "__main__":
    main()
